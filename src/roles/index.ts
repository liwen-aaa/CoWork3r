/**
 * 角色规约层出口。
 *
 * 职责：给每个窗口装上「你是谁、你能干什么、你不能干什么」，并保证它真的在上下文里。
 *
 * ── 为什么不用 pi skill ──────────────────────────────────
 * pi 的 skill 机制是**渐进披露**：只有 description 常驻 system prompt，全文靠模型
 * 自己决定去 read，pi 文档自己写了 "models don't always do this"。
 * 规约要的恰恰相反——它必须**永远在上下文里**。这不是 skill 机制不好，是语义不匹配：
 * skill 是「需要时查的手册」，规约是「你是谁」。
 *
 * 第二个理由是隔离：三份 skill 在三个窗口都可发现，dev 看得见 tester 的规约，
 * 而 D-01（生产者不能自证完成）依赖的正是两个上下文互不知情。
 *
 * 第三个理由是那次真实事故：老仓库的链条是 `bat 里的 --skill 路径` →
 * `.pi/skills/<项目>-<角色>/`，两处必须字符级一致。`paper-arch` 与 `paper-architect`
 * 差三个字母，扩展静默失活，排查半天还归因错了一半。规约由扩展自己按角色加载后,
 * 选规约的和激活扩展的是同一个变量，**结构上不可能错配**（D-03）。
 *
 * ── 规约里写什么 ──────────────────────────────────────────
 * 老仓库三份 SKILL 共 242 行，混了三类东西。分开：
 *   角色行为（「没写测试 = FAIL」）              ← 留在规约
 *   项目事实（「规划书在哪」）                    ← 走 03-config，运行时注入
 *   流程说明（「消息怎么投递、谁会被唤醒」）      ← 删掉，工具 description 已经说了
 *
 * 第三类是最大的浪费：三份各花二三十行讲消息系统怎么工作，而模型只需要知道
 * 「调这个工具」。工具 description 全量进上下文，讲两遍是纯付费重复（D-04）。
 * 目标长度各 40 行以内（老仓库是 72/81/89），守它的是 G6 与 R6。
 *
 * 不负责：
 * - **项目事实** —— 一个字都不写，全走 03-config 的 roleNotes
 * - **工具说明** —— 工具怎么用看 description
 * - **挂钩子** —— 接到 pi 的事件上是 07-adapter 的事（M6）
 * - **纪律兑现** —— 规约里写的东西如果没有对应 gate，它就会被跳过（D-02）
 *
 * 已知取舍：
 * - **每轮都注入。** `before_agent_start` 每轮触发，所以规约每轮拼一次。
 *   system prompt 本来每次请求都发全量，不累积、不额外花钱。想改成「只第一轮注入」
 *   做不到——`session_start` 没有 systemPrompt 口。接受。
 * - **规约是标准 markdown，不引入私有语法。** 这样单窗口降级时人能直接打开照着做，
 *   也是「不用 pi skill」这个决定唯一真实的代价（跨 harness 可移植性）的补法。
 */
