/**
 * 规划书解析层出口。
 *
 * 职责：把一份人写的 markdown 变成结构化断言，让四个读者（arch / dev / tester / gate）
 * 绑同一份东西。
 *
 * ── 为什么它是独立一层 ────────────────────────────────────
 * 老仓库有一件实测确认过的事：`planQualityGate(paper, 'docs/plan.md', 'M1')` → false，
 * M2/M3/M4 同样 false。**四个里程碑全部通不过 gate，而它们全都真的通过了人工验收。**
 *
 * 原因是格式分裂：模板产出的是行内 `验收：...`，而 gate 认的是 `### 验收断言方向`
 * 小节。两种格式从来没对齐过，而且没人发现——因为没人真跑过 arch 分发那条路径。
 *
 * 这是整套东西里最核心的失效：断言源是四个读者的公约，但它没有解析器。
 * 人读散文、gate 读正则，两边理解不一致时**没有任何信号**。
 *
 * 所以本层的存在理由是：**语法只定义一次，模板和 gate 都从它派生。**
 * 模板是解析器的可运行示例（L8 让它进测试），gate 调本层的输出而不自己写正则。
 *
 * ── 两套相反的编号规则 ────────────────────────────────────
 * 断言（S4）：位置编号。`M1` 的第 3 条 = `M1.3`。插入会导致后面重编——这看起来像
 *   缺陷，实际是把 D-14 编进了数据结构：想插断言就得动已有编号，动了就露馅。
 *   给断言配显式 id 反而会让「悄悄改一条断言的内容」变得无痕。
 * 未决（S5）：稳定 id，从文本读，**删行不回收**。因为未决定了就删行、位置会漂，
 *   而 `/research P2` 必须始终指向同一条（规格文字待订，见未决 P8）。
 *
 * 不负责：
 * - **写** —— 解析器只读。规划书由人写，arch 只改状态标记与未决/风险节（D-15）
 * - **判定里程碑通过** —— 那是 05-gates 跑测试 + 07-adapter 走流程
 * - **回答未决** —— frontier 只说「哪几条能动了」，谁去动是 07/08 的事
 * - **冻结** —— 本层只报告 `passed: true`，拦住修改是规约 + 未来的 hash 比对
 * - **校验语义** —— `[auto]` 里那个命令能不能跑、`涉及` 里的路径存不存在都不查。
 *   查了会误伤（路径可能是本里程碑要新建的），真跑不动会在 05-gates 暴露
 */
